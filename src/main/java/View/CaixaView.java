   public void carregarDadosTela() {
    try {
       
        List<Produto> produto = ProdutoJPA.filtrarTodos();
        cbProduto.removeAllItems();
        for (Produto p : produto) {
            cbProduto.addItem(p);
        }
        
        List<Cliente> cliente = ClienteJPA.filtrarTodos();
        cbCliente.removeAllItems(); 
        for (Cliente c : cliente) {
            cbCliente.addItem(c); 
        }
        
         List<Caixa> caixa = CaixaJPA.filtrarTodos();
        cbMetodo.removeAllItems(); 
        for (Caixa c : caixa) {
            cbMetodo.addItem(c); 
        }
        
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Erro ao carregar dados da tela: " + e.getMessage());
    }
}
    
