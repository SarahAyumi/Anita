    private void excluirJBActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_excluirJBActionPerformed
      int linhaSelecionada = jTable1.getSelectedRow();

    if (linhaSelecionada == -1) {
    JOptionPane.showMessageDialog(this, "Selecione um item na tabela para excluir.");
    return;
}


    int idReal = Integer.parseInt(jTable1.getValueAt(linhaSelecionada, 0).toString());

    int resposta = JOptionPane.showConfirmDialog(this, "Deseja realmente excluir este produto?", "Confirmação", JOptionPane.YES_NO_OPTION);
    if (resposta == JOptionPane.YES_OPTION) {
    try {
        ClienteJPA.removerCliente(idReal);
        
        JOptionPane.showMessageDialog(this, "Produto excluído com sucesso!");
        
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Erro ao excluir: " + e.getMessage());
    }
}
    }//GEN-LAST:event_excluirJBActionPerformed

    private void adicionarJBActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_adicionarJBActionPerformed
        try {
        
        Produto produtoSelecionado = (Produto) cbProduto.getSelectedItem(); 
        
        if (produtoSelecionado == null) {
            JOptionPane.showMessageDialog(this, "Por favor, selecione um produto!");
            return;
        }

        
        int quantidade = (int) sQuantidade.getValue();
        if (quantidade <= 0) {
            JOptionPane.showMessageDialog(this, "A quantidade deve ser maior do que zero!");
            return;
        }

        
        double precoUnitario = produtoSelecionado.getPreco(); 
        double subtotalLinha = quantidade * precoUnitario;

        DefaultTableModel modeloLocal = (DefaultTableModel) jTable1.getModel();
        
        Object[] novaLinha = {
            produtoSelecionado.getIdProduto(),
            produtoSelecionado.getNome(),
            quantidade,
            String.format("%.2f", precoUnitario),
            String.format("%.2f", subtotalLinha)
        };
        
        modeloLocal.addRow(novaLinha);

        this.valorTotalGeral += subtotalLinha;

        lblValorTotal.setText("Total: R$ " + String.format("%.2f", this.valorTotalGeral));

        sQuantidade.setValue(1);

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Erro ao adicionar item: " + e.getMessage());
        e.printStackTrace();
    }
    }//GEN-LAST:event_adicionarJBActionPerformed

    private void finalizarJBActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_finalizarJBActionPerformed
       
     String metodoPagamento = cbMetodo.getSelectedItem().toString();
    if (metodoPagamento == null) {
    JOptionPane.showMessageDialog(this, "Por favor, selecione um método!");
    return; 
    }
    
    Cliente clienteSelecionado = (Cliente) cbCliente.getSelectedItem();
    if (clienteSelecionado == null) {
    JOptionPane.showMessageDialog(this, "Por favor, selecione um cliente!");
    return; 
    }

    Produto produtoSelecionado = (Produto) cbProduto.getSelectedItem();

    if (produtoSelecionado == null) {
    JOptionPane.showMessageDialog(this, "Por favor, selecione um produto!");
    return; 
    }

    double valorFinal = this.valorTotalGeral;
    
    Produto produto = (Produto) cbProduto.getSelectedItem();
            int qtdUsada = (int) sQuantidade.getValue();

            produto.consumirMaterial(qtdUsada); 

            ProdutoJPA.atualizarProdutosJPQL(
            produto.getIdProduto(), 
            produto.getNome(), 
            produto.getArtista(), 
            produto.getPreco(),
            produto.getCategoria(),
            produto.getEstoqueP()
            );
    
    
    Caixa caixa = new Caixa(0, valorFinal, metodoPagamento, clienteSelecionado, produtoSelecionado);
            CaixaJPA.cadastrar(caixa);
            
             DefaultTableModel modeloLocal = (DefaultTableModel) jTable1.getModel();
            modeloLocal.setRowCount(0); 
        
            this.valorTotalGeral = 0.0; 
            lblValorTotal.setText("Total: R$ 0,00");

            JOptionPane.showMessageDialog(this, "Cadastro cadastrada com sucesso!");
    }//GEN-LAST:event_finalizarJBActionPerformed

