    private void atualizarJBActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_atualizarJBActionPerformed
        
        
        int linhaSelecionada = jTable1.getSelectedRow();
        if (linhaSelecionada == -1) {
            JOptionPane.showMessageDialog(this, "Selecione uma venda na tabela para atualizar.");
            return;
        }
         try {
            
        if (jTable1.isEditing()) {
         jTable1.getCellEditor().stopCellEditing();
        }
        
        try {
            
    int id = Integer.parseInt(jTable1.getValueAt(linhaSelecionada, 0).toString());
    double preco = Double.parseDouble(jTable1.getValueAt(linhaSelecionada, 1).toString().replace(",", "."));
    String metodo = jTable1.getValueAt(linhaSelecionada, 2).toString();
    String clienteNome = jTable1.getValueAt(linhaSelecionada, 3).toString();
    String produtoNome = jTable1.getValueAt(linhaSelecionada, 4).toString();
    
    
    CaixaJPA jpaInstancia = new CaixaJPA(); 
    jpaInstancia.atualizarCaixaJPQL(id, preco, metodo, clienteNome, produtoNome);

    JOptionPane.showMessageDialog(null, "Dados atualizados com sucesso!");

    }//GEN-LAST:event_atualizarJBActionPerformed
     catch (Exception e) {
         System.out.println("Erro ao atualizar dados: " + e.getMessage());
    }
    }catch (Exception e) {
         System.out.println("Erro ao atualizar: " + e.getMessage());
    }
    }    
    private void excluirJBActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_excluirJBActionPerformed
        int linhaSelecionada = jTable1.getSelectedRow();

    if (linhaSelecionada == -1) {
    JOptionPane.showMessageDialog(this, "Selecione uma venda na tabela para excluir.");
    return;
}


    int idReal = Integer.parseInt(jTable1.getValueAt(linhaSelecionada, 0).toString());

    int resposta = JOptionPane.showConfirmDialog(this, "Deseja realmente excluir esta venda?", "Confirmação", JOptionPane.YES_NO_OPTION);
    if (resposta == JOptionPane.YES_OPTION) {
    try {
        ClienteJPA.removerCliente(idReal);
        
        JOptionPane.showMessageDialog(this, "Venda excluída com sucesso!");
        
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Erro ao excluir: " + e.getMessage());
    }
}
    }//GEN-LAST:event_excluirJBActionPerformed

