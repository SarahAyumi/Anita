    private DefaultTableModel montarTabela(List<Caixa> lista) {
        
         DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
        
        String[] colunas = {"ID", "preço total", "Método pago", "Cliente", "Produto"};
        DefaultTableModel tabela = new DefaultTableModel();
        tabela.setColumnIdentifiers(colunas);
        
         if (lista == null || lista.isEmpty()) {
        return tabela; 
    }
        
        for (int i = 0; lista.size() > i; i++) {
            Caixa c = lista.get(i);
            
        StringBuilder nomesProdutos = new StringBuilder();
        if (c.getProduto() != null) {
            for (Produto p : c.getProduto()) {
                if (nomesProdutos.length() > 0) {
                    nomesProdutos.append(", ");
                }
                nomesProdutos.append(p.getNome()); 
            }
        }
       
    String nomeCliente = "Sem Cliente";


    if (c.getCliente() != null) {
    nomeCliente = c.getCliente().getNome(); 
    }
             
            String[] linha = {
                Integer.toString(c.getIdCaixa()),
                Double.toString (c.getPrecoTotal()),
                c.getMetodoPago(),
                nomeCliente,
                nomesProdutos.toString()
            };
            tabela.addRow(linha);
        }
        return tabela;
    }
    
