    public DefaultTableModel montarTabela(List<MateriaPrima> lista) {
        DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
        String[] colunas = {"ID", "nome", "estoque", "marca", "precoUn"};
        DefaultTableModel tabela = new DefaultTableModel();
        tabela.setColumnIdentifiers(colunas);
        
         if (lista == null || lista.isEmpty()) {
        return tabela; 
    }
        
        
        for (int i = 0; i < lista.size(); i++) { 
        MateriaPrima m = lista.get(i);
        
        
                 Object[] linha = {
                m.getIdMateriaPrima(), 
                m.getNome(),
                Integer.toString(m.getEstoque_M()),
                m.getMarca(),
                Double.toString (m.getPrecoUn()),
                
        };
            tabela.addRow(linha);
        }
        return tabela;
    }
    
    
