    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
       try {
           
            String nome = txtNome.getText().trim();
            String artista = txtArtista.getText().trim();
            String preco = txtPreco.getText().trim();
            String categoria = cbCategoria.getSelectedItem().toString();
            int estoque = (int) sEstoque.getValue();
            MateriaPrima materiaPrimaSelecionada = (MateriaPrima) cbMateriaPrima.getSelectedItem();

            
            if (nome.isEmpty() || categoria.isEmpty()|| artista.isEmpty() || preco.isEmpty() || estoque<= 0 ) {
                JOptionPane.showMessageDialog(this, "Todos os campos obrigatórios devem ser preenchidos!");
                return;
            }
            
            if (!preco.matches("\\d+(,\\d{2})?")) {
                JOptionPane.showMessageDialog(this, "Preço inválido!");
                return;
            }
            
            double precoConvertido = Double.parseDouble(preco.replace(",", "."));
            
            MateriaPrima material = (MateriaPrima) cbMateriaPrima.getSelectedItem();
            int qtdUsada = (int) sQuantidade.getValue();

            material.consumirMaterial(qtdUsada); 

            MateriaPrimaJPA.atualizarMateriaPrimaJPQL(
            material.getIdMateriaPrima(), 
            material.getNome(), 
            material.getEstoque_M(), 
            material.getMarca(), 
            material.getPrecoUn()
            );
            
            Produto produto = new Produto(0, nome, artista, precoConvertido, categoria, estoque, 5, materiaPrimaSelecionada, null);
            ProdutoJPA.cadastrar(produto);

             List<Produto> listaAtualizada = ProdutoJPA.filtrarTodos(); 
             telaPai.montarTabela(listaAtualizada);
             
            JOptionPane.showMessageDialog(this, "Cadastro cadastrada com sucesso!");
            this.dispose();

        
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro inesperado: " + e.getMessage());
        }
    }//GEN-LAST:event_jButton1ActionPerformed

