    public void carregarDadosTela() {
    try {
       
        List<Produto> produto = ProdutoJPA.filtrarTodos();
        cbCategoria.removeAllItems();
         for (Produto p : produto) {
        cbCategoria.addItem(p.getCategoria()); 
        }
        
        List<MateriaPrima> materiaPrima = MateriaPrimaJPA.filtrarTodos();
        cbMateriaPrima.removeAllItems(); 
        for (MateriaPrima mp : materiaPrima) {
            cbMateriaPrima.addItem(mp); 
            
        }
        
        
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Erro ao carregar dados da tela: " + e.getMessage());
    }
}
    
