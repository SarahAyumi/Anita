    private void atualizarJBActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_atualizarJBActionPerformed
                int linhaSelecionada = jTable1.getSelectedRow();
        
        if (linhaSelecionada == -1) {
            JOptionPane.showMessageDialog(this, "Selecione um cliente na tabela para atualizar.");
            return;
        }
         try {
             
        if (jTable1.isEditing()) {
         jTable1.getCellEditor().stopCellEditing();
        }
        
        try {
        Cliente c = new Cliente();
        int id = Integer.parseInt(jTable1.getValueAt(linhaSelecionada, 0).toString());
        String nome = jTable1.getValueAt(linhaSelecionada, 1).toString();
        String celular = jTable1.getValueAt(linhaSelecionada, 2).toString();
        String email = jTable1.getValueAt(linhaSelecionada, 3).toString();
        String dataN = jTable1.getValueAt(linhaSelecionada, 4).toString();

        String dataProntaParaOBanco = null;

        
        if (dataN != null && !dataN.equals("Não informada") && !dataN.trim().isEmpty()) {
        dataProntaParaOBanco = ClienteJPA.converterParaSQL(dataN);
        
        }
        ClienteJPA dao = new ClienteJPA();
        dao.atualizarClienteJPQL(id, nome, celular, email, dataProntaParaOBanco); 
        
        
        
        JOptionPane.showMessageDialog(this, "Cliente atualizado com sucesso!");
         }catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro ao atualizar dados: "+ e.getMessage());
     }   //JOptionPane.showMessageDialog
        }catch (Exception e) {
             JOptionPane.showMessageDialog(this, "Erro ao atualizar: "+ e.getMessage());
    }//GEN-LAST:event_atualizarJBActionPerformed
    }
    private void excluirJBActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_excluirJBActionPerformed
         int linhaSelecionada = jTable1.getSelectedRow();

    if (linhaSelecionada == -1) {
    JOptionPane.showMessageDialog(this, "Selecione um cliente na tabela para excluir.");
    return;
}


    int idReal = Integer.parseInt(jTable1.getValueAt(linhaSelecionada, 0).toString());

    int resposta = JOptionPane.showConfirmDialog(this, "Deseja realmente excluir este cliente?", "Confirmação", JOptionPane.YES_NO_OPTION);
    if (resposta == JOptionPane.YES_OPTION) {
    try {
        ClienteJPA.removerCliente(idReal);
        
        JOptionPane.showMessageDialog(this, "Cliente excluído com sucesso!");
        
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Erro ao excluir: " + e.getMessage());
    }
}
    }//GEN-LAST:event_excluirJBActionPerformed

