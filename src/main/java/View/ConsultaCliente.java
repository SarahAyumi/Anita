    public DefaultTableModel montarTabela(List<Cliente> lista) {
        
        DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
        
        String[] colunas = {"ID", "nome", "celular", "email", "data de nascimento"};
        DefaultTableModel tabela = new DefaultTableModel();
        tabela.setColumnIdentifiers(colunas);
        
         if (lista == null || lista.isEmpty()) {
        return tabela; 
    }
        
        
        for (int i = 0; i < lista.size(); i++) { 
        Cliente c = lista.get(i);
        
        String dataStr = "Não informada";
        if (c.getDataNascimento() != null) {
            dataStr = c.getDataNascimento().toString(); 
        }
            
                 Object[] linha = {
                c.getIdCliente(), 
                c.getNome(),
                c.getCelular(),
                c.getEmail(),
                dataStr
        };
            tabela.addRow(linha);
        }
        return tabela;
    }
    
